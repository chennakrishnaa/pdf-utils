/**
 * Runs every engine operation through [PdfJobs] on a device, with the real MuPDF native
 * library from the AAR and real `ContentResolver` file Uris. Inputs are generated by
 * [Fixtures] into the app's cache; outputs are saved to a cache file and read back.
 */
@RunWith(AndroidJUnit4::class)
class EngineOnDeviceTest {
    private val context: Context = InstrumentationRegistry.getInstrumentation().targetContext
    private lateinit var dir: File
    private val jobs: PdfJobs get() = PdfJobs.get(context)
    private val jobsRoot: File get() = File(context.cacheDir, "jobs")

    @Before
    fun setUp() {
        assertTrue("application is ${context.applicationContext}", context.applicationContext is PdfUtilApp)
        dir = File(context.cacheDir, "ondevice-${System.nanoTime()}").apply { mkdirs() }
        // Start every test from an empty jobs directory, whatever an earlier test (or class) left,
        // so one failure cannot cascade into every later assertJobsEmpty().
        jobs.wipeAll()
        assertJobsEmpty()
    }

    @After
    fun tearDown() {
        dir.deleteRecursively()
    }

    // ---------------------------------------------------------------- helpers

    private fun uri(f: File): Uri = Uri.fromFile(f)

    private fun pdf(f: File) = JobInput.Pdf(uri(f))

    private fun image(f: File) = JobInput.Image(uri(f))

    private fun run(
        inputs: List<JobInput>,
        block: (PdfEngine, List<File>, File, JobControl) -> PdfResult,
    ): JobOutcome = runBlocking {
        val progress = mutableListOf<Pair<Int, Int>>()
        jobs.run(inputs, { d, t -> progress += d to t }, block)
    }

    /**
     * Asserts Ready, saves the output to a cache file via a file Uri and returns it. A successful
     * save keeps the pending output (so it can be saved again or shared); this asserts that, then
     * discards it and asserts nothing is left under `cacheDir/jobs`.
     */
    private fun saveReady(outcome: JobOutcome, expectedPages: Int): File {
        if (outcome !is JobOutcome.Ready) fail("expected Ready, got $outcome")
        val ready = outcome as JobOutcome.Ready
        val dest = File(dir, "saved-${System.nanoTime()}.pdf")
        try {
            assertEquals("reported pages", expectedPages, ready.output.pages)
            assertTrue("output exists in cache", ready.output.file.isFile)
            assertEquals("reported bytes", ready.output.file.length(), ready.output.bytes)
            val saved = runBlocking { jobs.save(ready.output, uri(dest)) }
            assertTrue("save failed: ${saved.exceptionOrNull()}", saved.isSuccess)
            assertTrue(dest.isFile)
            assertEquals(ready.output.bytes, dest.length())
            // Save keeps the output; the input copies are already gone, so only the output is left.
            val jobDir = ready.output.file.parentFile!!
            assertTrue("output kept after save", ready.output.file.isFile)
            assertEquals("output unchanged by save", ready.output.bytes, ready.output.file.length())
            assertEquals("only this job is in cacheDir/jobs", listOf(jobDir), jobsRoot.listFiles()?.toList().orEmpty())
            assertEquals("only the output is left in the job dir", listOf(ready.output.file), jobDir.listFiles()?.toList().orEmpty())
            jobs.discard(ready.output)
            assertFalse("output deleted by discard", ready.output.file.exists())
            assertJobsEmpty()
        } finally {
            // Already discarded on success (discard is idempotent); after a failed assertion this
            // keeps the job directory from leaking into later tests and classes.
            jobs.discard(ready.output)
        }
        assertEquals("page count read back", expectedPages, Fixtures.pageCount(dest))
        return dest
    }

    private fun assertFailed(outcome: JobOutcome, expected: PdfError) {
        assertEquals(JobOutcome.Failed(expected), outcome)
        assertJobsEmpty()
    }

    private fun assertJobsEmpty() {
        val left = jobsRoot.listFiles()?.toList().orEmpty()
        assertTrue("cacheDir/jobs not empty: $left", left.isEmpty())
    }

    private fun assertSize(w: Float, h: Float, actual: Pair<Float, Float>, label: String) {
        assertTrue("$label: expected ${w}x$h, got $actual", abs(actual.first - w) < 1f && abs(actual.second - h) < 1f)
    }

    // ---------------------------------------------------------------- operations

    @Test
    fun imagesToPdf_jpegPngAndExifRotatedJpeg() {
        val jpeg = Fixtures.jpeg(dir, "a.jpg", width = 640, height = 480)
        val png = Fixtures.png(dir, "b.png", width = 400, height = 300)
        val rotated = Fixtures.jpegWithExifOrientation(dir, "rot.jpg", 300, 200, 6)

        val out = saveReady(
            run(listOf(image(jpeg), image(png), image(rotated))) { e, files, o, j ->
                e.imagesToPdf(files, PageSize.FIT_IMAGE, o, j)
            },
            expectedPages = 3,
        )

        val sizes = Fixtures.pageSizes(out)
        assertSize(640f, 480f, sizes[0], "jpeg page")
        assertSize(400f, 300f, sizes[1], "png page")
        assertSize(200f, 300f, sizes[2], "rotated page is upright (portrait)")

        val c = Fixtures.renderCornerColors(out, 2)
        assertTrue("TL ${c.topLeft.toString(16)}", Fixtures.colorNear(c.topLeft, Fixtures.RED))
        assertTrue("TR ${c.topRight.toString(16)}", Fixtures.colorNear(c.topRight, Fixtures.GREEN))
        assertTrue("BL ${c.bottomLeft.toString(16)}", Fixtures.colorNear(c.bottomLeft, Fixtures.BLUE))
        assertTrue("BR ${c.bottomRight.toString(16)}", Fixtures.colorNear(c.bottomRight, Fixtures.YELLOW))

        val infos = Fixtures.imageInfos(out)
        assertTrue(
            "plain JPEG embedded unchanged (${jpeg.length()} bytes): $infos",
            infos.any { it.filter == "DCTDecode" && it.width == 640 && it.rawLength == jpeg.length().toInt() },
        )
    }

    @Test
    fun imagesToPdf_webpMadeOnDevice() {
        val bmp = Bitmap.createBitmap(320, 240, Bitmap.Config.ARGB_8888)
        for (y in 0 until 240) for (x in 0 until 320) {
            bmp.setPixel(x, y, Color.rgb(x * 255 / 320, y * 255 / 240, 128))
        }
        val webp = File(dir, "pic.webp")
        @Suppress("DEPRECATION")
        val format = if (Build.VERSION.SDK_INT >= 30) Bitmap.CompressFormat.WEBP_LOSSLESS else Bitmap.CompressFormat.WEBP
        webp.outputStream().use { assertTrue(bmp.compress(format, 100, it)) }
        bmp.recycle()

        val transcodesBefore = app.venkat.offkit.core.ImageNormalizer.transcodeCountInThisProcess
        val out = saveReady(
            run(listOf(image(webp))) { e, files, o, j -> e.imagesToPdf(files, PageSize.FIT_IMAGE, o, j) },
            expectedPages = 1,
        )
        assertSize(320f, 240f, Fixtures.pageSizes(out)[0], "webp page")

        // PI2: the WebP was decoded in the :engine process, not in this (UI) process.
        assertEquals(
            "WebP decoded in the UI process",
            transcodesBefore,
            app.venkat.offkit.core.ImageNormalizer.transcodeCountInThisProcess,
        )
        val remote = (context.applicationContext as PdfUtilApp).engine as RemoteEngine
        val am = context.getSystemService(ActivityManager::class.java)
        val enginePid = am.runningAppProcesses.orEmpty()
            .firstOrNull { it.processName == "${context.packageName}:engine" }?.pid
        assertTrue("prepared by ${remote.lastImagePreparedByPid}, test pid ${Process.myPid()}",
            remote.lastImagePreparedByPid != 0 && remote.lastImagePreparedByPid != Process.myPid())
        assertEquals("normalised by the :engine process", enginePid, remote.lastImagePreparedByPid)
    }

    @Test
    fun merge_textTextAndLink() {
        val a = Fixtures.textPdf(dir, "a.pdf", listOf("Alpha one", "Alpha two"))
        val b = Fixtures.textPdf(dir, "b.pdf", listOf("Beta one", "Beta two", "Beta three"))
        val link = Fixtures.linkPdf(dir, "link.pdf", "https://example.com/x")

        val out = saveReady(
            run(listOf(pdf(a), pdf(b), pdf(link))) { e, files, o, j -> e.merge(files, o, j) },
            expectedPages = 6,
        )

        val texts = Fixtures.pageTexts(out)
        val expected = listOf("Alpha one", "Alpha two", "Beta one", "Beta two", "Beta three")
        expected.forEachIndexed { i, t -> assertTrue("page $i '${texts[i]}' lacks '$t'", texts[i].contains(t)) }
        val links = Fixtures.links(out, 5)
        assertEquals(1, links.size)
        assertEquals("https://example.com/x", links[0].first)
    }

    @Test
    fun compress_photoPdfHigh() {
        val input = Fixtures.photoPdf(dir, "photo.pdf", pages = 2, imageWidth = 2400, imageHeight = 1800)
        val textsBefore = Fixtures.pageTexts(input)

        val out = saveReady(
            run(listOf(pdf(input))) { e, files, o, j -> e.compress(files[0], CompressionLevel.HIGH, o, j) },
            expectedPages = 2,
        )

        assertTrue("not smaller: ${out.length()} >= ${input.length()}", out.length() < input.length())
        assertEquals(textsBefore, Fixtures.pageTexts(out))
        val infos = Fixtures.imageInfos(out).filter { !it.isMaskTarget }
        assertEquals("images: $infos", 2, infos.size)
        for (info in infos) assertEquals("long edge of $info", 1000, maxOf(info.width, info.height))
    }

    @Test
    fun appendImages_twoImagesAfterTextPdf() {
        val doc = Fixtures.textPdf(dir, "doc.pdf", listOf("First page", "Last page"), pageWidth = 400f, pageHeight = 300f)
        val jpeg = Fixtures.jpeg(dir, "a.jpg", width = 300, height = 400)
        val png = Fixtures.png(dir, "b.png", width = 400, height = 300)

        val out = saveReady(
            run(listOf(pdf(doc), image(jpeg), image(png))) { e, files, o, j ->
                e.appendImages(files[0], files.drop(1), o, j)
            },
            expectedPages = 4,
        )

        val texts = Fixtures.pageTexts(out)
        assertTrue(texts[0], texts[0].contains("First page"))
        assertTrue(texts[1], texts[1].contains("Last page"))
        val sizes = Fixtures.pageSizes(out)
        assertSize(400f, 300f, sizes[2], "appended page 1")
        assertSize(400f, 300f, sizes[3], "appended page 2")
    }

    @Test
    fun imagesToPdf_highCompressionIsSmallerWithSamePageSizes() {
        val a = Fixtures.jpeg(dir, "a.jpg", width = 2400, height = 1800, seed = 3L)
        val b = Fixtures.jpeg(dir, "b.jpg", width = 2400, height = 1800, seed = 4L)
        val inputs = listOf(image(a), image(b))

        val plain = saveReady(
            run(inputs) { e, files, o, j -> e.imagesToPdf(files, PageSize.FIT_IMAGE, o, j, compression = null) },
            expectedPages = 2,
        )
        val high = saveReady(
            run(inputs) { e, files, o, j ->
                e.imagesToPdf(files, PageSize.FIT_IMAGE, o, j, compression = CompressionLevel.HIGH)
            },
            expectedPages = 2,
        )

        assertTrue("not smaller: ${high.length()} >= ${plain.length()}", high.length() < plain.length())
        assertEquals(Fixtures.pageSizes(plain), Fixtures.pageSizes(high))
        val infos = Fixtures.imageInfos(high).filter { !it.isMaskTarget }
        assertEquals("images: $infos", 2, infos.size)
        for (info in infos) assertEquals("long edge of $info", 1000, maxOf(info.width, info.height))
    }

    @Test
    fun estimateImage_levelsDecreaseAndJobsEmpty() {
        val jpeg = Fixtures.jpeg(dir, "big.jpg", width = 2400, height = 1800, seed = 5L)
        val estimate = runBlocking { jobs.estimateImage(uri(jpeg)) }
        if (estimate !is PdfEstimate.Ok) fail("expected Ok, got $estimate")
        val ok = estimate as PdfEstimate.Ok
        val low = ok.byLevel.getValue(CompressionLevel.LOW)
        val medium = ok.byLevel.getValue(CompressionLevel.MEDIUM)
        val high = ok.byLevel.getValue(CompressionLevel.HIGH)
        assertTrue("not decreasing: $ok", low > medium && medium > high)
        for ((level, bytes) in ok.byLevel) assertTrue("$level $bytes > original ${ok.original}", bytes <= ok.original)
        assertJobsEmpty()
    }

    @Test
    fun engineRunsInSeparateEngineProcess() {
        val app = context.applicationContext as PdfUtilApp
        assertTrue("engine is ${app.engine}", app.engine is RemoteEngine)
        val good = Fixtures.textPdf(dir, "p.pdf", listOf("Process"))
        val outcome = run(listOf(pdf(good))) { e, files, o, j -> e.merge(files, o, j) }
        saveReady(outcome, expectedPages = 1)
        val am = context.getSystemService(ActivityManager::class.java)
        val engineProc = am.runningAppProcesses.orEmpty().firstOrNull { it.processName == "${context.packageName}:engine" }
        if (engineProc == null) fail("no :engine process in ${am.runningAppProcesses?.map { it.processName }}")
        assertTrue("engine pid ${engineProc!!.pid} vs ${Process.myPid()}", engineProc.pid != Process.myPid())
    }

